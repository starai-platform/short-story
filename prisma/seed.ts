async function main() {
  for (const item of templates) {
    const existing = await prisma.promptType.findFirst({ where: { ownerId: null, name: item.name, deletedAt: null } });
    if (existing) {
      const promptChanged = existing.description !== item.description
        || existing.outlineTemplate !== item.outlineTemplate
        || existing.chapterTemplate !== item.chapterTemplate;
      await prisma.promptType.update({
        where: { id: existing.id },
        data: { ...item, isActive: true, ...(promptChanged ? { version: { increment: 1 } } : {}) },
      });
    } else {
      await prisma.promptType.create({ data: item });
    }
  }

  const adminEmail = (process.env.ADMIN_EMAILS || process.env.ADMIN_EMAIL || "")
    .split(",")[0]
    .trim()
    .toLowerCase();
  const adminPassword = process.env.ADMIN_PASSWORD || "";
  if (adminEmail && adminPassword.length >= 8 && adminPassword.length <= 72) {
    const existingAdmin = await prisma.user.findUnique({ where: { email: adminEmail } });
    if (!existingAdmin) {
      await prisma.user.create({
        data: { email: adminEmail, passwordHash: await bcrypt.hash(adminPassword, 12) },
      });
      process.stdout.write(`[账户] 已创建管理员账号：${adminEmail}\n`);
    } else if (process.env.SQLITE_BOOTSTRAP_ADMIN === "true") {
      await prisma.user.update({
        where: { email: adminEmail },
        data: { passwordHash: await bcrypt.hash(adminPassword, 12), isActive: true },
      });
      process.stdout.write(`[账户] 已初始化管理员登录密码：${adminEmail}\n`);
    } else {
      process.stdout.write(`[账户] 管理员账号已存在：${adminEmail}（密码保持不变）\n`);
    }
  }
}

main()
  .then(() => prisma.$disconnect())
  .catch(async (error) => {
    console.error(error);
    await prisma.$disconnect();
    process.exit(1);
  });
